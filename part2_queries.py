def task_4_1(engine: Engine) -> None:
    header("4.1", "Delete withdrawn papers whose corresponding author is Amina Aminova")
    checks = [
        (
            "papers that are withdrawn OR have Amina as corresponding author",
            """
            SELECT p.paper_id, p.title, p.status, u.email AS corresponding_author_email
            FROM paper p
            LEFT JOIN paper_author pa ON pa.paper_id = p.paper_id AND pa.is_corresponding
            LEFT JOIN app_user u ON u.user_id = pa.author_id
            WHERE p.status = :status OR u.email = :email
            ORDER BY p.paper_id
            """,
            P_4_1,
        ),
        (
            "dependent rows of the papers that match the delete condition",
            """
            SELECT p.paper_id,
                   (SELECT COUNT(*) FROM paper_author  x WHERE x.paper_id = p.paper_id) AS authorships,
                   (SELECT COUNT(*) FROM paper_keyword x WHERE x.paper_id = p.paper_id) AS keywords,
                   (SELECT COUNT(*) FROM paper_version x WHERE x.paper_id = p.paper_id) AS versions,
                   (SELECT COUNT(*) FROM review        x WHERE x.paper_id = p.paper_id) AS reviews
            FROM paper p
            WHERE p.status = :status
              AND EXISTS (SELECT 1
                          FROM paper_author pa
                          JOIN app_user u ON u.user_id = pa.author_id
                          WHERE pa.paper_id = p.paper_id
                            AND pa.is_corresponding
                            AND u.email = :email)
            ORDER BY p.paper_id
            """,
            P_4_1,
        ),
        (
            "table totals (users, conferences and tracks must not change)",
            """
            SELECT (SELECT COUNT(*) FROM app_user)      AS users,
                   (SELECT COUNT(*) FROM conference)    AS conferences,
                   (SELECT COUNT(*) FROM track)         AS tracks,
                   (SELECT COUNT(*) FROM paper)         AS papers,
                   (SELECT COUNT(*) FROM paper_author)  AS authorships,
                   (SELECT COUNT(*) FROM paper_keyword) AS keywords,
                   (SELECT COUNT(*) FROM paper_version) AS versions,
                   (SELECT COUNT(*) FROM review)        AS reviews
            """,
            None,
        ),
    ]
    mutation_demo(engine, "4.1", checks, """
        DELETE FROM paper p
        WHERE p.status = :status
          AND EXISTS (SELECT 1
                      FROM paper_author pa
                      JOIN app_user u ON u.user_id = pa.author_id
                      WHERE pa.paper_id = p.paper_id
                        AND pa.is_corresponding
                        AND u.email = :email)
        RETURNING p.paper_id, p.title
    """, P_4_1, explanation=(
        "The single DELETE runs in one transaction; the foreign keys paper_author.paper_id,\n"
        "paper_keyword.paper_id, paper_version.paper_id and review.paper_id are declared\n"
        "ON DELETE CASCADE, so the dependent authorship, keyword, version and review rows are\n"
        "removed in the same statement. Users, tracks and conferences are untouched."))


