def task_6(engine: Engine) -> None:
    with engine.connect() as conn:
        header("6.1", "Per track: number of distinct papers and distinct authors (empty tracks = 0)")
        run_query(conn, "6.1", """
            SELECT t.track_id,
                   t.name                       AS track_name,
                   t.conference_id,
                   COUNT(DISTINCT p.paper_id)   AS paper_count,
                   COUNT(DISTINCT pa.author_id) AS author_count
            FROM track t
            LEFT JOIN paper p         ON p.track_id = t.track_id
            LEFT JOIN paper_author pa ON pa.paper_id = p.paper_id
            GROUP BY t.track_id, t.name, t.conference_id
            ORDER BY t.track_id
        """)

        header("6.2", "Per reviewer: completed reviews and average overall score (no reviews = 0 / NULL)")
        run_query(conn, "6.2", """
            SELECT r.reviewer_id,
                   u.given_name || ' ' || u.surname AS full_name,
                   COUNT(rv.review_id)              AS review_count,
                   ROUND(AVG(rv.overall_score), 2)  AS avg_overall_score
            FROM reviewer r
            JOIN app_user u     ON u.user_id = r.reviewer_id
            LEFT JOIN review rv ON rv.reviewer_id = r.reviewer_id
            GROUP BY r.reviewer_id, u.given_name, u.surname
            ORDER BY r.reviewer_id
        """)

        header("6.3", "Per conference: total papers, accepted papers, average review score")
        print("Paper counts and the review average are aggregated in separate CTEs, so papers with\n"
              "several reviews are not counted more than once and each review counts once.")
        run_query(conn, "6.3", """
            WITH paper_counts AS (
                SELECT t.conference_id,
                       COUNT(*)                                       AS total_papers,
                       COUNT(*) FILTER (WHERE p.status = 'accepted')  AS accepted_papers
                FROM paper p
                JOIN track t ON t.track_id = p.track_id
                GROUP BY t.conference_id
            ),
            review_avgs AS (
                SELECT t.conference_id,
                       AVG(rv.overall_score) AS avg_score
                FROM review rv
                JOIN paper p ON p.paper_id = rv.paper_id
                JOIN track t ON t.track_id = p.track_id
                GROUP BY t.conference_id
            )
            SELECT c.conference_id,
                   c.acronym,
                   COALESCE(pc.total_papers, 0)    AS total_papers,
                   COALESCE(pc.accepted_papers, 0) AS accepted_papers,
                   ROUND(ra.avg_score, 2)          AS avg_overall_score
            FROM conference c
            LEFT JOIN paper_counts pc ON pc.conference_id = c.conference_id
            LEFT JOIN review_avgs  ra ON ra.conference_id = c.conference_id
            ORDER BY c.conference_id
        """)

        header("6.4", "Reviewers with more completed reviews than the average per reviewer")
        run_query(conn, "6.4", """
            WITH reviewer_counts AS (
                SELECT r.reviewer_id,
                       COUNT(rv.review_id) AS review_count
                FROM reviewer r
                LEFT JOIN review rv ON rv.reviewer_id = r.reviewer_id
                GROUP BY r.reviewer_id
            ),
            overall AS (
                SELECT AVG(review_count) AS avg_reviews_per_reviewer
                FROM reviewer_counts               -- includes reviewers with 0 reviews
            )
            SELECT rc.reviewer_id,
                   u.given_name || ' ' || u.surname     AS full_name,
                   rc.review_count,
                   ROUND(o.avg_reviews_per_reviewer, 2) AS avg_reviews_per_reviewer
            FROM reviewer_counts rc
            JOIN app_user u ON u.user_id = rc.reviewer_id
            CROSS JOIN overall o
            WHERE rc.review_count > o.avg_reviews_per_reviewer
            ORDER BY rc.review_count DESC, rc.reviewer_id
        """)


