def show_sql(sql: str, params: dict | None) -> None:
    print("SQL:")
    print(textwrap.indent(textwrap.dedent(sql).strip(), "    "))
    if params:
        print(f"Parameters: {params}")


def run_query(conn: Connection, label: str, sql: str, params: dict | None = None, max_width: int = 60):
    """Execute a SELECT and print the SQL, the bound parameters and the result."""
    print(f"\n--- {label} ---")
    show_sql(sql, params)
    result = conn.execute(text(sql), params or {})
    columns = list(result.keys())
    rows = result.fetchall()
    print("Result:")
    print_table(columns, rows, max_width)
    return [tuple(r) for r in rows]


def run_dml(conn: Connection, label: str, sql: str, params: dict) -> int:
    """Execute an UPDATE/DELETE ... RETURNING and print affected rows and rowcount."""
    print(f"\n--- {label} ---")
    show_sql(sql, params)
    result = conn.execute(text(sql), params)
    rowcount = result.rowcount          # read while the cursor is still open
    columns = list(result.keys())
    rows = result.fetchall()
    print(f"Rows affected (rowcount): {rowcount}")
    print("RETURNING:")
    print_table(columns, rows)
    return rowcount


def mutation_demo(engine: Engine, number: str, checks, mutation_sql: str, params: dict,
                  explanation: str = "") -> None:
    """BEFORE checks -> mutation -> AFTER checks -> ROLLBACK -> verify seed data restored.

    checks: list of (title, sql, params) SELECT statements shown before and after.
    """
    with engine.connect() as conn:
        trans = conn.begin()
        try:
            before = [run_query(conn, f"{number} BEFORE: {t}", s, p) for t, s, p in checks]
            affected = run_dml(conn, f"{number} STATEMENT", mutation_sql, params)
            if explanation:
                print(explanation)
            for t, s, p in checks:
                run_query(conn, f"{number} AFTER: {t}", s, p)
        finally:
            trans.rollback()
        print(f"\nTransaction ROLLED BACK ({affected} row(s) were affected inside it).")

        restored = [[tuple(r) for r in conn.execute(text(s), p or {}).fetchall()] for _, s, p in checks]
        same = all(b == r for b, r in zip(before, restored, strict=True))
        print(f"Seed data restored after rollback: {'YES - identical to BEFORE' if same else 'NO'}")
        conn.rollback()


