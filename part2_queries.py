def task_5(engine: Engine) -> None:
    with engine.connect() as conn:
        header("5.1", "Accepted papers with corresponding author, track and conference")
        run_query(conn, "5.1", """
            SELECT p.paper_id,
                   p.title,
                   u.given_name || ' ' || u.surname AS corresponding_author,
                   u.email                          AS corresponding_author_email,
                   t.name                           AS track_name,
                   c.conference_id,
                   c.acronym
            FROM paper p
            JOIN track t      ON t.track_id = p.track_id
            JOIN conference c ON c.conference_id = t.conference_id
            LEFT JOIN paper_author pa ON pa.paper_id = p.paper_id AND pa.is_corresponding
            LEFT JOIN app_user u      ON u.user_id = pa.author_id
            WHERE p.status = :status
            ORDER BY p.paper_id
        """, P_5_1)

        header("5.2", "Papers whose abstract contains 'machine learning' (case-insensitive)")
        run_query(conn, "5.2", """
            SELECT paper_id, title
            FROM paper
            WHERE abstract ILIKE :pattern
            ORDER BY paper_id
        """, P_5_2)

        header("5.3", "All versions of a selected paper, highest version number first")
        run_query(conn, "5.3", """
            SELECT version_no, file_location, uploaded_at
            FROM paper_version
            WHERE paper_id = :paper_id
            ORDER BY version_no DESC
        """, P_5_3)

        header("5.4", "Pool reviewers of a conference with 'Databases' expertise and >= 3 years")
        run_query(conn, "5.4", """
            SELECT r.reviewer_id,
                   u.given_name || ' ' || u.surname AS full_name,
                   u.email
            FROM conference_reviewer cr
            JOIN reviewer r ON r.reviewer_id = cr.reviewer_id
            JOIN app_user u ON u.user_id = r.reviewer_id
            WHERE cr.conference_id = :conference_id
              AND r.years_experience >= :min_years
              AND EXISTS (SELECT 1
                          FROM reviewer_expertise re
                          WHERE re.reviewer_id = r.reviewer_id
                            AND re.area_label = :expertise)
            ORDER BY r.reviewer_id
        """, P_5_4)


