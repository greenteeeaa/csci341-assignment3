def task_1(engine: Engine) -> None:
    header("1", "Create statements (tables and constraints from sql/schema.sql)")
    script = read_sql("schema.sql")
    print("Executing the following DDL script through SQLAlchemy "
          "(Connection.exec_driver_sql inside one transaction):\n")
    print(textwrap.indent(script.strip(), "    "))
    with engine.begin() as conn:
        run_script(conn, script)
    print("\nSchema created and committed.")

    with engine.connect() as conn:
        run_query(conn, "1 VERIFY: tables created", """
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
            ORDER BY table_name
        """)
        run_query(conn, "1 VERIFY: constraints created", """
            SELECT cl.relname AS table_name,
                   con.conname AS constraint_name,
                   CASE con.contype WHEN 'p' THEN 'PRIMARY KEY' WHEN 'f' THEN 'FOREIGN KEY'
                                    WHEN 'u' THEN 'UNIQUE' WHEN 'c' THEN 'CHECK' END AS constraint_type,
                   pg_get_constraintdef(con.oid) AS definition
            FROM pg_constraint con
            JOIN pg_class cl ON cl.oid = con.conrelid
            JOIN pg_namespace ns ON ns.oid = cl.relnamespace
            WHERE ns.nspname = 'public'
            ORDER BY cl.relname, con.contype DESC, con.conname
        """, max_width=130)
        run_query(conn, "1 VERIFY: secondary indexes, incl. the partial UNIQUE index "
                        "uq_paper_one_corresponding (at most one corresponding author per paper)", """
            SELECT tablename, indexname, indexdef
            FROM pg_indexes
            WHERE schemaname = 'public'
              AND indexname NOT IN (SELECT conname FROM pg_constraint)
            ORDER BY tablename, indexname
        """, max_width=130)


def row_counts(conn: Connection, label: str) -> None:
    sql = "\nUNION ALL\n".join(
        f"SELECT '{t}' AS table_name, COUNT(*) AS row_count FROM {t}" for t in TABLES)
    run_query(conn, label, sql)


