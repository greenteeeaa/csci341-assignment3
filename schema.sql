-- =====================================================================
-- CSCI 341 Assignment 3
-- Research Conference and Paper Review Management System
-- Schema (DDL) for PostgreSQL 13 or later (tested on PostgreSQL 16)
--
-- The script is repeatable: it drops the existing objects first.
-- Run it from Python (part2_queries.py, init_db.py) or with
--     psql -d conference_db -1 -f sql/schema.sql
-- =====================================================================

DROP VIEW IF EXISTS accepted_paper_schedule;

DROP TABLE IF EXISTS
    review,
    paper_version,
    paper_author,
    paper_keyword,
    paper,
    conference_session,
    track,
    conference_reviewer,
    conference_host,
    conference,
    reviewer_expertise,
    reviewer,
    author_research_area,
    author,
    app_user
CASCADE;

-- ---------------------------------------------------------------------
-- Users and their two roles (disjoint = no, complete = yes:
-- every user is an author, a reviewer, or both)
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    given_name    VARCHAR(100) NOT NULL,
    surname       VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    affiliation   VARCHAR(200) NOT NULL,
    country       VARCHAR(100) NOT NULL,
    phone_number  VARCHAR(30)  NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_email_format CHECK (POSITION('@' IN email) > 1),
    CONSTRAINT ck_app_user_names_not_blank CHECK (TRIM(given_name) <> '' AND TRIM(surname) <> ''),
    CONSTRAINT ck_app_user_phone_format CHECK (phone_number ~ '^[+]?[0-9 ()-]{5,30}$')
);

CREATE TABLE author (
    author_id  INTEGER     NOT NULL,
    orcid      VARCHAR(19),                       -- optional
    CONSTRAINT pk_author PRIMARY KEY (author_id),
    CONSTRAINT fk_author_user FOREIGN KEY (author_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT uq_author_orcid UNIQUE (orcid),
    CONSTRAINT ck_author_orcid_format CHECK (
        orcid IS NULL OR orcid ~ '^[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]$')
);

-- multivalued attribute: research-area labels of an author
CREATE TABLE author_research_area (
    author_id   INTEGER      NOT NULL,
    area_label  VARCHAR(100) NOT NULL,
    CONSTRAINT pk_author_research_area PRIMARY KEY (author_id, area_label),
    CONSTRAINT fk_ara_author FOREIGN KEY (author_id)
        REFERENCES author (author_id) ON DELETE CASCADE,
    CONSTRAINT ck_ara_label_not_blank CHECK (TRIM(area_label) <> '')
);

CREATE TABLE reviewer (
    reviewer_id       INTEGER NOT NULL,
    years_experience  INTEGER NOT NULL,
    CONSTRAINT pk_reviewer PRIMARY KEY (reviewer_id),
    CONSTRAINT fk_reviewer_user FOREIGN KEY (reviewer_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_reviewer_experience_nonnegative CHECK (years_experience >= 0)
);

-- multivalued attribute: expertise-area labels of a reviewer
CREATE TABLE reviewer_expertise (
    reviewer_id  INTEGER      NOT NULL,
    area_label   VARCHAR(100) NOT NULL,
    CONSTRAINT pk_reviewer_expertise PRIMARY KEY (reviewer_id, area_label),
    CONSTRAINT fk_re_reviewer FOREIGN KEY (reviewer_id)
        REFERENCES reviewer (reviewer_id) ON DELETE CASCADE,
    CONSTRAINT ck_re_label_not_blank CHECK (TRIM(area_label) <> '')
);

-- ---------------------------------------------------------------------
-- Conferences, host institutions, reviewer pools
-- ---------------------------------------------------------------------
CREATE TABLE conference (
    conference_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name                 VARCHAR(200) NOT NULL,
    acronym              VARCHAR(30)  NOT NULL,
    description          TEXT         NOT NULL,
    city                 VARCHAR(100) NOT NULL,
    country              VARCHAR(100) NOT NULL,
    start_date           DATE         NOT NULL,
    end_date             DATE         NOT NULL,
    submission_deadline  DATE         NOT NULL,
    review_deadline      DATE         NOT NULL,
    CONSTRAINT pk_conference PRIMARY KEY (conference_id),
    CONSTRAINT ck_conference_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_conference_deadlines CHECK (review_deadline >= submission_deadline)
);

-- multivalued attribute: host institutions of a conference
CREATE TABLE conference_host (
    conference_id  INTEGER      NOT NULL,
    host_name      VARCHAR(200) NOT NULL,
    CONSTRAINT pk_conference_host PRIMARY KEY (conference_id, host_name),
    CONSTRAINT fk_ch_conference FOREIGN KEY (conference_id)
        REFERENCES conference (conference_id) ON DELETE CASCADE,
    CONSTRAINT ck_ch_host_not_blank CHECK (TRIM(host_name) <> '')
);

-- M:N reviewer pool. Deleting a conference removes only the pool
-- memberships, never the reviewer or user records.
CREATE TABLE conference_reviewer (
    conference_id  INTEGER NOT NULL,
    reviewer_id    INTEGER NOT NULL,
    CONSTRAINT pk_conference_reviewer PRIMARY KEY (conference_id, reviewer_id),
    CONSTRAINT fk_cr_conference FOREIGN KEY (conference_id)
        REFERENCES conference (conference_id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_reviewer FOREIGN KEY (reviewer_id)
        REFERENCES reviewer (reviewer_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Tracks and sessions
-- ---------------------------------------------------------------------
CREATE TABLE track (
    track_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    conference_id   INTEGER      NOT NULL,
    name            VARCHAR(200) NOT NULL,
    description     TEXT         NOT NULL,
    research_area   VARCHAR(100) NOT NULL,
    coordinator_id  INTEGER      NOT NULL,
    CONSTRAINT pk_track PRIMARY KEY (track_id),
    CONSTRAINT uq_track_name_per_conference UNIQUE (conference_id, name),
    CONSTRAINT fk_track_conference FOREIGN KEY (conference_id)
        REFERENCES conference (conference_id) ON DELETE CASCADE,
    CONSTRAINT fk_track_coordinator FOREIGN KEY (coordinator_id)
        REFERENCES reviewer (reviewer_id) ON DELETE RESTRICT,
    -- optional rule enforced by the DBMS: coordinator is in the conference's pool
    CONSTRAINT fk_track_coordinator_in_pool FOREIGN KEY (conference_id, coordinator_id)
        REFERENCES conference_reviewer (conference_id, reviewer_id)
);

CREATE TABLE conference_session (
    session_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    conference_id  INTEGER      NOT NULL,
    title          VARCHAR(200) NOT NULL,
    session_date   DATE         NOT NULL,
    start_time     TIME(0)      NOT NULL,
    end_time       TIME(0)      NOT NULL,
    room_label     VARCHAR(100) NOT NULL,
    chair_id       INTEGER      NOT NULL,
    CONSTRAINT pk_conference_session PRIMARY KEY (session_id),
    CONSTRAINT fk_session_conference FOREIGN KEY (conference_id)
        REFERENCES conference (conference_id) ON DELETE CASCADE,
    CONSTRAINT fk_session_chair FOREIGN KEY (chair_id)
        REFERENCES reviewer (reviewer_id) ON DELETE RESTRICT,
    -- optional rule enforced by the DBMS: chair is in the conference's pool
    CONSTRAINT fk_session_chair_in_pool FOREIGN KEY (conference_id, chair_id)
        REFERENCES conference_reviewer (conference_id, reviewer_id),
    CONSTRAINT ck_session_times CHECK (end_time > start_time)
);

-- ---------------------------------------------------------------------
-- Papers and their dependents
-- ---------------------------------------------------------------------
CREATE TABLE paper (
    paper_id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    track_id         INTEGER      NOT NULL,
    title            VARCHAR(300) NOT NULL,
    abstract         TEXT         NOT NULL,
    submission_date  DATE         NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'submitted',
    session_id       INTEGER,                     -- optional: NULL = not scheduled
    CONSTRAINT pk_paper PRIMARY KEY (paper_id),
    CONSTRAINT fk_paper_track FOREIGN KEY (track_id)
        REFERENCES track (track_id) ON DELETE RESTRICT,
    CONSTRAINT fk_paper_session FOREIGN KEY (session_id)
        REFERENCES conference_session (session_id) ON DELETE SET NULL,
    CONSTRAINT ck_paper_status CHECK (
        status IN ('submitted', 'under review', 'accepted', 'rejected', 'withdrawn')),
    -- safety net for application check 2: only accepted papers can be scheduled
    CONSTRAINT ck_paper_session_requires_accepted CHECK (
        session_id IS NULL OR status = 'accepted')
);

-- multivalued attribute: keywords of a paper
CREATE TABLE paper_keyword (
    paper_id  INTEGER      NOT NULL,
    keyword   VARCHAR(100) NOT NULL,
    CONSTRAINT pk_paper_keyword PRIMARY KEY (paper_id, keyword),
    CONSTRAINT fk_pk_paper FOREIGN KEY (paper_id)
        REFERENCES paper (paper_id) ON DELETE CASCADE,
    CONSTRAINT ck_pk_keyword_not_blank CHECK (TRIM(keyword) <> '')
);

-- M:N authorship with relationship attributes
CREATE TABLE paper_author (
    paper_id          INTEGER NOT NULL,
    author_id         INTEGER NOT NULL,
    author_position   INTEGER NOT NULL,
    is_corresponding  BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_paper_author PRIMARY KEY (paper_id, author_id),
    CONSTRAINT uq_paper_author_position UNIQUE (paper_id, author_position),
    CONSTRAINT fk_pa_paper FOREIGN KEY (paper_id)
        REFERENCES paper (paper_id) ON DELETE CASCADE,
    CONSTRAINT fk_pa_author FOREIGN KEY (author_id)
        REFERENCES author (author_id) ON DELETE RESTRICT,
    CONSTRAINT ck_pa_position_positive CHECK (author_position > 0)
);

-- at most one corresponding author per paper (the application ensures "at least one")
CREATE UNIQUE INDEX uq_paper_one_corresponding
    ON paper_author (paper_id) WHERE is_corresponding;

-- weak entity: identified by (paper_id, version_no); gaps in version_no are allowed
CREATE TABLE paper_version (
    paper_id       INTEGER      NOT NULL,
    version_no     INTEGER      NOT NULL,
    file_location  VARCHAR(500) NOT NULL,
    uploaded_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    change_note    TEXT,                          -- optional
    CONSTRAINT pk_paper_version PRIMARY KEY (paper_id, version_no),
    CONSTRAINT fk_pv_paper FOREIGN KEY (paper_id)
        REFERENCES paper (paper_id) ON DELETE CASCADE,
    CONSTRAINT ck_pv_version_positive CHECK (version_no > 0),
    CONSTRAINT ck_pv_location_not_blank CHECK (TRIM(file_location) <> '')
);

-- only completed reviews are stored, so every mandatory field is NOT NULL
CREATE TABLE review (
    review_id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    paper_id                INTEGER     NOT NULL,
    reviewer_id             INTEGER     NOT NULL,
    overall_score           INTEGER     NOT NULL,
    recommendation          VARCHAR(10) NOT NULL,
    comments_for_authors    TEXT        NOT NULL,
    confidential_comments   TEXT,                 -- optional
    review_submission_date  DATE        NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_review PRIMARY KEY (review_id),
    CONSTRAINT uq_review_paper_reviewer UNIQUE (paper_id, reviewer_id),
    CONSTRAINT fk_review_paper FOREIGN KEY (paper_id)
        REFERENCES paper (paper_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_reviewer FOREIGN KEY (reviewer_id)
        REFERENCES reviewer (reviewer_id) ON DELETE RESTRICT,
    CONSTRAINT ck_review_score CHECK (overall_score BETWEEN 1 AND 5),
    CONSTRAINT ck_review_recommendation CHECK (recommendation IN ('accept', 'reject')),
    CONSTRAINT ck_review_comments_not_blank CHECK (TRIM(comments_for_authors) <> '')
);

-- ---------------------------------------------------------------------
-- Secondary indexes on foreign keys and frequently filtered columns
-- ---------------------------------------------------------------------
CREATE INDEX ix_conference_reviewer_reviewer ON conference_reviewer (reviewer_id);
CREATE INDEX ix_reviewer_expertise_label     ON reviewer_expertise (area_label);
CREATE INDEX ix_track_conference             ON track (conference_id);
CREATE INDEX ix_track_coordinator            ON track (coordinator_id);
CREATE INDEX ix_session_conference           ON conference_session (conference_id);
CREATE INDEX ix_session_chair                ON conference_session (chair_id);
CREATE INDEX ix_paper_track                  ON paper (track_id);
CREATE INDEX ix_paper_session                ON paper (session_id);
CREATE INDEX ix_paper_status                 ON paper (status);
CREATE INDEX ix_paper_author_author          ON paper_author (author_id);
CREATE INDEX ix_review_reviewer              ON review (reviewer_id);
